import { readFileSync } from 'node:fs';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { config, createConfig } from '../../lib/provider/immobiliare.js';
import { resolveSearch, readPage, readDetail } from '../../lib/services/immobiliare/mobile-api.js';
import logger from '../../lib/services/logger.js';

vi.mock('../../lib/services/immobiliare/mobile-api.js', () => ({
  resolveSearch: vi.fn(),
  readPage: vi.fn(),
  readDetail: vi.fn(),
}));
const SEARCH = 'https://www.immobiliare.it/affitto-case/roma/';
const recorded = JSON.parse(readFileSync(new URL('../testFixtures/immobiliare_list.json', import.meta.url), 'utf8'));
const detail = JSON.parse(readFileSync(new URL('../testFixtures/immobiliare_detail.json', import.meta.url), 'utf8'));
const params = { c: 6737, cat: 1, t: 'a', px: 600 };
const advert = (id) => ({ ...structuredClone(recorded.list[0]), id });
const page = (list, totalActive = list.length) => ({ list, count: list.length, totalActive });

beforeEach(() => {
  vi.clearAllMocks();
  resolveSearch.mockResolvedValue({ type: 'search', params });
});
afterEach(() => vi.restoreAllMocks());

describe('Immobiliare.it native adverts', () => {
  it('normalizes machine decimals, coordinates, dates and canonical identity', () => {
    expect(config.normalize(recorded.list[0])).toMatchObject({
      link: 'https://www.immobiliare.it/annunci/134261367/',
      price: 500,
      size: 117,
      rooms: 4,
      address: 'Via satrico, 65, Rome',
      latitude: 41.8766,
      longitude: 12.5089,
      publishedAt: 1793364033000,
    });
    expect(config.normalize(recorded.list[0]).title).toContain('Via satrico');
    const raw = advert(42);
    raw.price.raw = 1200.5;
    raw.topology.surface.size = 42.5;
    expect(config.normalize(raw)).toMatchObject({ price: 1200.5, size: 42.5 });
  });

  it('does not invent missing figures or expose hidden prices', () => {
    const raw = advert(42);
    raw.price.isHidden = true;
    raw.topology = {};
    raw.geography = {};
    expect(config.normalize(raw)).toMatchObject({
      price: null,
      rooms: null,
      size: null,
      address: null,
      latitude: undefined,
    });
    expect(config.normalize({}).link).toBeNull();
  });

  it('refuses nonfinite coordinates and missing dates', () => {
    const raw = advert(42);
    raw.creationDate = null;
    raw.lastModified = null;
    raw.geography.geolocation = { latitude: 100, longitude: Infinity };
    expect(config.normalize(raw)).toMatchObject({ latitude: undefined, longitude: undefined, publishedAt: undefined });
  });

  it('keeps the gallery and a full description from a recorded detail', () => {
    const parsed = config.normalize(detail);
    expect(parsed.description).toContain('Via Satrico');
    expect(parsed.images.length).toBeGreaterThan(1);
    expect(parsed.image).toMatch(/^https:\/\/pwm\.im-cdn\.it\//);
  });

  it('changes the price hash while keeping the portal link', () => {
    const raw = advert(42);
    const before = config.normalize(raw);
    raw.price.raw += 10;
    const after = config.normalize(raw);
    expect(after.id).not.toBe(before.id);
    expect(after.link).toBe(before.link);
  });

  it('keeps URL and blacklist state separate between jobs', () => {
    const one = createConfig({ url: SEARCH }, ['satrico']);
    const two = createConfig({ url: SEARCH.replace('roma', 'milano') });
    const listing = config.normalize(recorded.list[0]);
    expect(one.filter(listing)).toBe(false);
    expect(two.filter(listing)).toBe(true);
    expect(config.url).toBeNull();
    expect(config.filter).toBeUndefined();
    expect(two.filter({ title: null })).toBe(false);
  });
});

describe('Immobiliare.it API search', () => {
  it('accepts generic search links generated by the portal form', async () => {
    readPage.mockResolvedValue(page([advert(1)]));
    const url = 'https://www.immobiliare.it/search-list/?idComune=6737&idContratto=2&idCategoria=1&prezzoMassimo=600';
    await config.getListings(url);
    expect(resolveSearch).toHaveBeenCalledWith(url);
  });
  it('hands filters to the portal resolver and starts from zero, without a browser', async () => {
    readPage.mockResolvedValue(page([advert(1)]));
    await config.getListings(`${SEARCH}?pag=9&prezzoMassimo=600&arredato=on&futureFilter=yes`);
    const resolvedUrl = new URL(resolveSearch.mock.calls[0][0]);
    expect(resolvedUrl.searchParams.has('pag')).toBe(false);
    expect(resolvedUrl.searchParams.get('futureFilter')).toBe('yes');
    expect(resolvedUrl.searchParams.get('arredato')).toBe('on');
    expect(readPage).toHaveBeenCalledWith(params, 0);
    expect(config.needsBrowser).toBe(false);
  });

  it('walks native offsets and deduplicates promoted adverts by portal id', async () => {
    readPage
      .mockReset()
      .mockResolvedValueOnce(page([advert(1), advert(2)], 4))
      .mockResolvedValueOnce(page([advert(2), advert(3)], 4));
    expect((await config.getListings(SEARCH)).map((x) => x.id)).toEqual([1, 2, 3]);
    expect(readPage).toHaveBeenNthCalledWith(2, params, 2);
  });

  it('advances past a project-only page', async () => {
    const project = advert(1);
    project.rty = 'project';
    readPage
      .mockReset()
      .mockResolvedValueOnce(page([project], 2))
      .mockResolvedValueOnce(page([advert(2)], 2));
    expect((await config.getListings(SEARCH)).map((x) => x.id)).toEqual([2]);
  });

  it('skips disabled adverts and multi-unit offers', async () => {
    const disabled = advert(1);
    disabled.enabled = false;
    const multi = advert(2);
    multi.subProperties = [{}];
    readPage.mockResolvedValue(page([disabled, multi, advert(3)]));
    expect((await config.getListings(SEARCH)).map((x) => x.id)).toEqual([3]);
  });

  it('distinguishes empty results from unreadable data', async () => {
    readPage.mockResolvedValueOnce(page([]));
    expect(await config.getListings(SEARCH)).toEqual([]);
    readPage.mockResolvedValueOnce({ error: 'not results' });
    await expect(config.getListings(SEARCH)).rejects.toThrow('no listing array');
  });

  it.each([null, {}, { type: 'detail', params }, { type: 'search', params: [] }, { type: 'search', params: {} }])(
    'rejects an unresolved search: %s',
    async (value) => {
      resolveSearch.mockResolvedValue(value);
      await expect(config.getListings(SEARCH)).rejects.toThrow('could not resolve');
      expect(readPage).not.toHaveBeenCalled();
    },
  );

  it('reports a blocked first page as a failure', async () => {
    readPage.mockRejectedValueOnce(new Error('verification required'));
    await expect(config.getListings(SEARCH)).rejects.toThrow('verification required');
  });

  it('keeps earlier results with a warning if a later page fails', async () => {
    const warn = vi.spyOn(logger, 'warn').mockImplementation(() => {});
    readPage
      .mockReset()
      .mockResolvedValueOnce(page([advert(1)], 20))
      .mockRejectedValueOnce(new Error('verification required'));
    expect(await config.getListings(SEARCH)).toHaveLength(1);
    expect(warn).toHaveBeenCalledWith(expect.stringContaining('incomplete'));
  });

  it('stops repeated pages and reports truncation', async () => {
    const warn = vi.spyOn(logger, 'warn').mockImplementation(() => {});
    readPage.mockResolvedValue(page([advert(1)], 100));
    expect(await config.getListings(SEARCH)).toHaveLength(1);
    expect(readPage).toHaveBeenCalledTimes(2);
    expect(warn).toHaveBeenCalledWith(expect.stringContaining('repeated'));
  });

  it('bounds a wide search', async () => {
    const warn = vi.spyOn(logger, 'warn').mockImplementation(() => {});
    let id = 0;
    readPage.mockImplementation(async () => page([advert(++id)], 100));
    expect(await config.getListings(SEARCH)).toHaveLength(20);
    expect(readPage).toHaveBeenCalledTimes(20);
    expect(warn).toHaveBeenCalledWith(expect.stringContaining('20 pages'));
  });

  it.each([
    'https://evil.test/affitto-case/roma/',
    'https://www.immobiliare.it.evil.test/affitto-case/roma/',
    'http://www.immobiliare.it/affitto-case/roma/',
    'https://user:password@www.immobiliare.it/affitto-case/roma/',
    'https://www.immobiliare.it:444/affitto-case/roma/',
    'https://www.immobiliare.it/annunci/123/',
  ])('rejects an invalid portal URL before a request: %s', async (url) => {
    await expect(config.getListings(url)).rejects.toThrow('HTTPS search URL');
    expect(resolveSearch).not.toHaveBeenCalled();
  });

  it('does not offer unverified active-listing probes', () => {
    expect(config.activityProbe).toBeUndefined();
    expect(config.browserActivityProbe).toBeUndefined();
  });
});

describe('Immobiliare.it details', () => {
  it('enriches the description without changing the search price or hash', async () => {
    const listing = config.normalize(recorded.list[0]);
    const id = listing.id;
    const raw = structuredClone(detail);
    raw.price.raw += 100;
    readDetail.mockResolvedValue(raw);
    await config.fetchDetails(listing);
    expect(listing.description).toContain('Via Satrico');
    expect(listing.price).toBe(500);
    expect(listing.id).toBe(id);
  });
  it('keeps a search card when detail is blocked or refers to a different advert', async () => {
    const listing = config.normalize(recorded.list[0]);
    readDetail.mockRejectedValueOnce(new Error('blocked'));
    expect(await config.fetchDetails(listing)).toBe(listing);
    readDetail.mockResolvedValueOnce({ ...detail, id: 1 });
    await config.fetchDetails(listing);
    expect(listing.description).toBeUndefined();
  });
});
